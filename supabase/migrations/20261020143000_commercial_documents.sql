create or replace function public.commercial_relationships_valid(
  p_client_id uuid, p_contact_id uuid, p_enquiry_id uuid, p_project_id uuid
)
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1 from public.clients c where c.id = p_client_id and c.archived = false
  ) and exists (
    select 1 from public.client_contacts cc
    where cc.id = p_contact_id and cc.client_id = p_client_id and cc.archived = false
  ) and (
    p_enquiry_id is null or exists (
      select 1 from public.enquiries e
      where e.id = p_enquiry_id and e.client_id = p_client_id and e.archived = false
    )
  ) and (
    p_project_id is null or exists (
      select 1 from public.projects p
      where p.id = p_project_id and p.client = p_client_id and p.archived = false
    )
  );
$$;

revoke all on function public.commercial_relationships_valid(uuid, uuid, uuid, uuid)
  from public, anon, authenticated, service_role;

create or replace function public.commercial_line_items_valid(p_items jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_item jsonb;
  v_quantity numeric;
  v_unit_amount numeric;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) not between 1 and 100 then
    return false;
  end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    begin
      v_quantity := (v_item ->> 'quantity')::numeric;
      v_unit_amount := (v_item ->> 'unit_amount')::numeric;
    exception when others then
      return false;
    end;
    if coalesce(btrim(v_item ->> 'description'), '') = ''
      or char_length(btrim(v_item ->> 'description')) > 500
      or v_quantity is null or v_quantity <= 0
      or v_quantity::text in ('NaN', 'Infinity', '-Infinity')
      or v_unit_amount is null or v_unit_amount < 0
      or v_unit_amount::text in ('NaN', 'Infinity', '-Infinity') then
      return false;
    end if;
  end loop;
  return true;
end;
$$;

revoke all on function public.commercial_line_items_valid(jsonb)
  from public, anon, authenticated, service_role;

create or replace function public.create_commercial_quote(p_quote jsonb, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_client_id uuid;
  v_contact_id uuid;
  v_enquiry_id uuid;
  v_project_id uuid;
  v_subtotal numeric(12,2);
  v_discount numeric(12,2);
  v_retainer numeric(5,2);
  v_quote_id uuid;
  v_settings public.ops_settings%rowtype;
begin
  if not public.is_admin(v_user_id) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  select * into v_settings from public.ops_settings limit 1;
  begin
    v_client_id := (p_quote ->> 'client_id')::uuid;
    v_contact_id := (p_quote ->> 'contact_id')::uuid;
    v_enquiry_id := nullif(p_quote ->> 'enquiry_id', '')::uuid;
    v_project_id := nullif(p_quote ->> 'project_id', '')::uuid;
    v_discount := coalesce((p_quote ->> 'discount_amount')::numeric, 0);
    v_retainer := coalesce(
      nullif(p_quote ->> 'retainer_percentage', '')::numeric,
      v_settings.default_retainer_percentage
    );
  exception when others then
    return jsonb_build_object('status', 'invalid', 'message', 'Invalid quote values.');
  end;
  if num_nonnulls(v_enquiry_id, v_project_id) > 1
    or not public.commercial_relationships_valid(
      v_client_id, v_contact_id, v_enquiry_id, v_project_id
    )
    or not public.commercial_line_items_valid(p_items)
    or coalesce(btrim(p_quote ->> 'title'), '') = ''
    or char_length(btrim(p_quote ->> 'title')) > 240
    or jsonb_typeof(coalesce(p_quote -> 'services', '[]'::jsonb)) is distinct from 'array'
    or v_discount::text in ('NaN', 'Infinity', '-Infinity')
    or v_retainer::text in ('NaN', 'Infinity', '-Infinity')
    or v_retainer <= 0 or v_retainer > 100 then
    return jsonb_build_object('status', 'invalid', 'message', 'Check the quote details.');
  end if;
  select round(sum((item ->> 'quantity')::numeric * (item ->> 'unit_amount')::numeric), 2)
    into v_subtotal from jsonb_array_elements(p_items) item;
  if v_discount < 0 or v_discount > v_subtotal then
    return jsonb_build_object('status', 'invalid', 'message', 'Discount cannot exceed subtotal.');
  end if;
  insert into public.commercial_quotes (
    client_id, contact_id, enquiry_id, project_id, title, overview, services, location,
    subtotal, discount_amount, total, retainer_percentage, terms,
    owner_user_id, owner_name, owner_email
  ) values (
    v_client_id, v_contact_id, v_enquiry_id, v_project_id, btrim(p_quote ->> 'title'),
    nullif(btrim(p_quote ->> 'overview'), ''),
    coalesce(array(select jsonb_array_elements_text(coalesce(p_quote -> 'services', '[]'))), '{}'),
    nullif(btrim(p_quote ->> 'location'), ''), v_subtotal, v_discount,
    v_subtotal - v_discount,
    v_retainer,
    coalesce(p_quote ->> 'terms', v_settings.default_quote_terms),
    v_user_id, btrim(p_quote ->> 'owner_name'), lower(btrim(p_quote ->> 'owner_email'))
  ) returning id into v_quote_id;
  insert into public.commercial_quote_line_items (
    quote_id, description, quantity, unit_amount, sort_order
  ) select v_quote_id, btrim(item.value ->> 'description'),
      (item.value ->> 'quantity')::numeric, (item.value ->> 'unit_amount')::numeric,
      item.ordinality - 1
    from jsonb_array_elements(p_items) with ordinality item;
  insert into public.ops_activity_log (message, collection, record_id, action)
  values ('Quote draft created', 'commercial_quotes', v_quote_id, 'created');
  return jsonb_build_object('status', 'ok', 'quote_id', v_quote_id);
end;
$$;

create or replace function public.revise_commercial_quote(
  p_quote_id uuid, p_expected_version integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_existing public.commercial_quotes%rowtype;
  v_revision_id uuid;
begin
  if not public.is_admin(v_user_id) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  select * into v_existing from public.commercial_quotes where id = p_quote_id for update;
  if not found then return jsonb_build_object('status', 'not-found'); end if;
  if v_existing.version is distinct from p_expected_version then
    return jsonb_build_object('status', 'conflict', 'version', v_existing.version);
  end if;
  if v_existing.status not in ('Sent', 'Expired') then
    return jsonb_build_object(
      'status', 'invalid', 'message', 'Only a sent or expired quote can be revised.'
    );
  end if;
  update public.commercial_quotes set status = 'Superseded', version = version + 1
    where id = p_quote_id;
  insert into public.commercial_quotes (
    reference_number, revision, supersedes_id, client_id, contact_id, enquiry_id, project_id,
    title, overview, services, location, subtotal, discount_amount, total,
    retainer_percentage, terms, owner_user_id, owner_name, owner_email
  ) values (
    v_existing.reference_number, v_existing.revision + 1, v_existing.id,
    v_existing.client_id, v_existing.contact_id, v_existing.enquiry_id, v_existing.project_id,
    v_existing.title, v_existing.overview, v_existing.services, v_existing.location,
    v_existing.subtotal, v_existing.discount_amount, v_existing.total,
    v_existing.retainer_percentage, v_existing.terms,
    v_user_id, v_existing.owner_name, v_existing.owner_email
  ) returning id into v_revision_id;
  insert into public.commercial_quote_line_items (
    quote_id, description, quantity, unit_amount, sort_order
  ) select v_revision_id, description, quantity, unit_amount, sort_order
    from public.commercial_quote_line_items where quote_id = p_quote_id;
  insert into public.ops_activity_log (message, collection, record_id, action) values
    ('Quote superseded by revision ' || (v_existing.revision + 1),
      'commercial_quotes', p_quote_id, 'superseded'),
    ('Quote revision created', 'commercial_quotes', v_revision_id, 'created');
  return jsonb_build_object('status', 'ok', 'quote_id', v_revision_id, 'version', 1);
end;
$$;

