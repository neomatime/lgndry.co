create or replace function public.record_commercial_payment(
  p_invoice_id uuid, p_payment jsonb, p_expected_version integer, p_recorder_name text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_invoice public.commercial_invoices%rowtype;
  v_quote public.commercial_quotes%rowtype;
  v_amount numeric(12,2);
  v_new_paid numeric(12,2);
  v_paid_on date;
  v_project_id uuid;
  v_enquiry record;
  v_created jsonb;
  v_project_type text;
begin
  if not public.is_admin(v_user_id) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  select * into v_invoice from public.commercial_invoices where id = p_invoice_id for update;
  if not found then return jsonb_build_object('status', 'not-found'); end if;
  if v_invoice.version is distinct from p_expected_version then
    return jsonb_build_object('status', 'conflict', 'version', v_invoice.version);
  end if;
  if v_invoice.status in ('Draft', 'Void', 'Paid') then
    return jsonb_build_object('status', 'invalid', 'message', 'Payment cannot be recorded.');
  end if;
  begin
    v_amount := (p_payment ->> 'amount')::numeric;
    v_paid_on := (p_payment ->> 'paid_on')::date;
  exception when others then
    return jsonb_build_object('status', 'invalid', 'message', 'Enter valid payment details.');
  end;
  v_new_paid := v_invoice.paid_amount + v_amount;
  if v_paid_on is null
    or v_amount::text in ('NaN', 'Infinity', '-Infinity')
    or v_amount <= 0 or v_new_paid > v_invoice.total
    or coalesce(p_payment ->> 'method', '') not in ('Bank Transfer', 'Card', 'Cash', 'Other') then
    return jsonb_build_object('status', 'invalid', 'message', 'Check the payment details.');
  end if;
  insert into public.commercial_payments (
    invoice_id, amount, paid_on, method, reference, notes, recorded_by, recorded_by_name
  ) values (
    p_invoice_id, v_amount, v_paid_on, p_payment ->> 'method',
    nullif(btrim(p_payment ->> 'reference'), ''), nullif(btrim(p_payment ->> 'notes'), ''),
    v_user_id, btrim(p_recorder_name)
  );
  update public.commercial_invoices set
    paid_amount = v_new_paid,
    status = case when v_new_paid = total then 'Paid' else status end,
    paid_at = case when v_new_paid = total then now() else null end,
    version = version + 1
  where id = p_invoice_id;
  if v_new_paid = v_invoice.total and v_invoice.billing_type = 'Deposit'
    and v_invoice.quote_id is not null then
    select * into v_quote from public.commercial_quotes where id = v_invoice.quote_id;
    v_project_id := v_invoice.project_id;
    if v_project_id is null and v_invoice.enquiry_id is not null then
      select id, client_id, project_type, description, location, timeline, archived
        into v_enquiry from public.enquiries where id = v_invoice.enquiry_id for update;
      select id into v_project_id from public.projects
        where enquiry_id = v_invoice.enquiry_id limit 1;
    end if;
    if v_project_id is null then
      if v_invoice.enquiry_id is not null and coalesce(v_enquiry.archived, true) then
        raise exception using errcode = 'P0001', message = 'linked enquiry is unavailable';
      end if;
      v_project_type := case
        when v_invoice.enquiry_id is not null
          and v_enquiry.project_type in ('Documentary', 'Event', 'Film', 'Visual Production')
          then v_enquiry.project_type else 'Other' end;
      v_created := public.create_project_with_plan(
        jsonb_build_object(
          'name', v_quote.title, 'client_id', v_quote.client_id,
          'client_contact_id', v_quote.contact_id, 'project_type', v_project_type,
          'services', to_jsonb(v_quote.services),
          'overview', coalesce(
            v_quote.overview,
            case when v_invoice.enquiry_id is not null then v_enquiry.description else null end
          ),
          'location', coalesce(
            v_quote.location,
            case when v_invoice.enquiry_id is not null then v_enquiry.location else null end
          ),
          'start_date', '', 'end_date', '',
          'schedule_notes', case
            when v_invoice.enquiry_id is not null then v_enquiry.timeline else null end,
          'people_resources', '', 'budget_min', '', 'budget_max', v_quote.total::text,
          'currency', 'ZAR', 'payment_status',
            case when v_quote.retainer_percentage = 100 then 'Paid' else 'Partially Paid' end,
          'delivery_status', 'Not Ready', 'status', 'Planning'
        ), '[]'::jsonb, '[]'::jsonb, '[]'::jsonb
      );
      if v_created ->> 'status' <> 'ok' then
        raise exception using errcode = 'P0001', message = 'project creation failed';
      end if;
      v_project_id := (v_created ->> 'project_id')::uuid;
      if v_invoice.enquiry_id is not null then
        update public.projects set enquiry_id = v_invoice.enquiry_id where id = v_project_id;
      end if;
    end if;
    if v_project_id is not null then
      if v_invoice.enquiry_id is not null then
        update public.enquiries set status = 'Booked' where id = v_invoice.enquiry_id;
      end if;
      update public.projects set payment_status = case
        when v_quote.retainer_percentage = 100 then 'Paid' else 'Partially Paid' end
      where id = v_project_id;
      update public.commercial_invoices set project_id = v_project_id where id = p_invoice_id;
      update public.commercial_quotes set project_id = v_project_id where id = v_quote.id;
    end if;
  end if;
  insert into public.ops_activity_log (message, collection, record_id, action)
  values ('Payment recorded: ZAR ' || to_char(v_amount, 'FM999999990.00'),
    'commercial_invoices', p_invoice_id, 'payment_recorded');
  return jsonb_build_object(
    'status', 'ok', 'version', v_invoice.version + 1,
    'paid', v_new_paid = v_invoice.total, 'project_id', v_project_id
  );
end;
$$;

create or replace function public.void_commercial_invoice(
  p_invoice_id uuid, p_expected_version integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare v_invoice public.commercial_invoices%rowtype;
begin
  if not public.is_admin((select auth.uid())) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  select * into v_invoice from public.commercial_invoices where id = p_invoice_id for update;
  if not found then return jsonb_build_object('status', 'not-found'); end if;
  if v_invoice.version is distinct from p_expected_version then
    return jsonb_build_object('status', 'conflict', 'version', v_invoice.version);
  end if;
  if v_invoice.paid_amount > 0 or v_invoice.status = 'Paid' then
    return jsonb_build_object('status', 'invalid', 'message', 'Paid invoices cannot be voided.');
  end if;
  update public.commercial_invoices set status = 'Void', voided_at = now(), version = version + 1
    where id = p_invoice_id;
  insert into public.ops_activity_log (message, collection, record_id, action)
  values ('Invoice voided', 'commercial_invoices', p_invoice_id, 'voided');
  return jsonb_build_object('status', 'ok', 'version', v_invoice.version + 1);
end;
$$;

