create or replace function public.issue_commercial_quote(
  p_quote_id uuid, p_token_hash text, p_expected_version integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_quote public.commercial_quotes%rowtype;
  v_settings public.ops_settings%rowtype;
begin
  if not public.is_admin((select auth.uid())) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  select * into v_quote from public.commercial_quotes where id = p_quote_id for update;
  if not found then return jsonb_build_object('status', 'not-found'); end if;
  if v_quote.version is distinct from p_expected_version then
    return jsonb_build_object('status', 'conflict', 'version', v_quote.version);
  end if;
  if v_quote.status not in ('Draft', 'Sent') then
    return jsonb_build_object('status', 'invalid', 'message', 'This quote cannot be sent.');
  end if;
  if v_quote.total <= 0 then
    return jsonb_build_object('status', 'invalid', 'message', 'A quote total must be greater than zero.');
  end if;
  select * into v_settings from public.ops_settings limit 1;
  if v_quote.status = 'Draft' and (
    coalesce(btrim(v_settings.company_email), '') = ''
    or coalesce(btrim(v_settings.business_address), '') = ''
    or coalesce(btrim(v_settings.bank_name), '') = ''
    or coalesce(btrim(v_settings.account_holder), '') = ''
    or coalesce(btrim(v_settings.account_number), '') = ''
    or coalesce(btrim(v_settings.sender_email), '') = ''
  ) then
    return jsonb_build_object(
      'status', 'invalid',
      'message', 'Complete the company, banking and sender details in Settings before sending.'
    );
  end if;
  update public.commercial_quotes set
    status = 'Sent', approval_token_hash = p_token_hash,
    issued_at = coalesce(issued_at, now()),
    valid_until = case when status = 'Draft'
      then current_date + v_settings.default_quote_validity_days else valid_until end,
    company_snapshot = case when status = 'Draft' then jsonb_build_object(
      'workspace_name', v_settings.workspace_name,
      'company_email', v_settings.company_email,
