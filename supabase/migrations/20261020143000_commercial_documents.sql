create or replace function public.approve_public_commercial_quote(p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_quote public.commercial_quotes%rowtype;
  v_contact public.client_contacts%rowtype;
  v_invoice_id uuid;
  v_deposit numeric(12,2);
  v_due_days integer;
begin
  select * into v_quote from public.commercial_quotes
  where approval_token_hash = p_token_hash for update;
  if not found or v_quote.status not in ('Sent', 'Approved') then
    return jsonb_build_object('status', 'not-found');
  end if;
  if v_quote.status = 'Approved' then
    select id into v_invoice_id from public.commercial_invoices
      where quote_id = v_quote.id and billing_type = 'Deposit';
    return jsonb_build_object('status', 'ok', 'invoice_id', v_invoice_id, 'already_approved', true);
  end if;
  if v_quote.valid_until < current_date then
    update public.commercial_quotes set status = 'Expired', version = version + 1
      where id = v_quote.id;
    return jsonb_build_object('status', 'expired');
  end if;
  select * into v_contact from public.client_contacts where id = v_quote.contact_id;
  v_deposit := round(v_quote.total * v_quote.retainer_percentage / 100, 2);
  v_due_days := coalesce((v_quote.payment_snapshot ->> 'deposit_due_days')::integer, 3);
  update public.commercial_quotes set
    status = 'Approved', approved_at = now(), approved_by_name = v_contact.full_name,
    approved_by_email = v_contact.email, version = version + 1
  where id = v_quote.id;
  insert into public.commercial_invoices (
    quote_id, client_id, contact_id, enquiry_id, project_id, title, overview,
    billing_type, status, subtotal, total, paid_amount, issue_date, due_date, sent_at,
    company_snapshot, payment_snapshot, terms_snapshot,
    owner_user_id, owner_name, owner_email
  ) values (
    v_quote.id, v_quote.client_id, v_quote.contact_id, v_quote.enquiry_id,
    v_quote.project_id, v_quote.title || ' - Booking Deposit', v_quote.overview,
    'Deposit', 'Sent', v_deposit, v_deposit, 0, current_date,
    current_date + v_due_days, now(), v_quote.company_snapshot, v_quote.payment_snapshot,
    v_quote.terms, v_quote.owner_user_id, v_quote.owner_name, v_quote.owner_email
  ) returning id into v_invoice_id;
  insert into public.commercial_invoice_line_items (
    invoice_id, description, quantity, unit_amount, sort_order
  ) values (
    v_invoice_id,
    'Booking retainer (' || trim(to_char(v_quote.retainer_percentage, 'FM999990.##')) || '%)',
    1, v_deposit, 0
  );
  insert into public.ops_activity_log (message, collection, record_id, action) values
    ('Quote approved by client', 'commercial_quotes', v_quote.id, 'approved'),
    ('Deposit invoice created from approved quote', 'commercial_invoices', v_invoice_id, 'created');
  return jsonb_build_object('status', 'ok', 'invoice_id', v_invoice_id, 'already_approved', false);
exception when unique_violation then
  select id into v_invoice_id from public.commercial_invoices
    where quote_id = v_quote.id and billing_type = 'Deposit';
  return jsonb_build_object('status', 'ok', 'invoice_id', v_invoice_id, 'already_approved', true);
end;
$$;

create or replace function public.create_commercial_invoice(p_invoice jsonb, p_items jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_settings public.ops_settings%rowtype;
  v_client_id uuid;
  v_contact_id uuid;
  v_enquiry_id uuid;
  v_project_id uuid;
  v_subtotal numeric(12,2);
  v_discount numeric(12,2);
  v_invoice_id uuid;
  v_issue_date date;
  v_due_date date;
begin
  if not public.is_admin(v_user_id) then
    raise exception using errcode = '42501', message = 'admin access required';
  end if;
  begin
    v_client_id := (p_invoice ->> 'client_id')::uuid;
    v_contact_id := (p_invoice ->> 'contact_id')::uuid;
    v_enquiry_id := nullif(p_invoice ->> 'enquiry_id', '')::uuid;
    v_project_id := nullif(p_invoice ->> 'project_id', '')::uuid;
    v_discount := coalesce((p_invoice ->> 'discount_amount')::numeric, 0);
    v_issue_date := nullif(p_invoice ->> 'issue_date', '')::date;
    v_due_date := nullif(p_invoice ->> 'due_date', '')::date;
  exception when others then
    return jsonb_build_object('status', 'invalid', 'message', 'Invalid invoice values.');
  end;
  if not public.commercial_relationships_valid(
      v_client_id, v_contact_id, v_enquiry_id, v_project_id
    ) or num_nonnulls(v_enquiry_id, v_project_id) > 1
    or not public.commercial_line_items_valid(p_items)
    or coalesce(btrim(p_invoice ->> 'title'), '') = ''
    or char_length(btrim(p_invoice ->> 'title')) > 240
    or coalesce(p_invoice ->> 'billing_type', 'Standard')
      not in ('Standard', 'Deposit', 'Balance')
    or v_discount::text in ('NaN', 'Infinity', '-Infinity')
    or (v_issue_date is not null and v_due_date is not null and v_issue_date > v_due_date) then
    return jsonb_build_object('status', 'invalid', 'message', 'Check the invoice details.');
  end if;
  select * into v_settings from public.ops_settings limit 1;
  select round(sum((item ->> 'quantity')::numeric * (item ->> 'unit_amount')::numeric), 2)
    into v_subtotal from jsonb_array_elements(p_items) item;
  if v_discount < 0 or v_discount > v_subtotal then
    return jsonb_build_object('status', 'invalid', 'message', 'Discount cannot exceed subtotal.');
  end if;
  insert into public.commercial_invoices (
    client_id, contact_id, enquiry_id, project_id, title, overview, notes, billing_type,
    subtotal, discount_amount, total, issue_date, due_date,
    company_snapshot, payment_snapshot, terms_snapshot,
    owner_user_id, owner_name, owner_email
  ) values (
    v_client_id, v_contact_id, v_enquiry_id, v_project_id, btrim(p_invoice ->> 'title'),
    nullif(btrim(p_invoice ->> 'overview'), ''), nullif(btrim(p_invoice ->> 'notes'), ''),
    coalesce(p_invoice ->> 'billing_type', 'Standard'), v_subtotal, v_discount,
    v_subtotal - v_discount, v_issue_date, v_due_date,
    jsonb_build_object(
      'workspace_name', v_settings.workspace_name, 'company_email', v_settings.company_email,
      'company_phone', v_settings.company_phone, 'website_url', v_settings.website_url,
      'business_address', v_settings.business_address,
      'registration_number', v_settings.registration_number,
      'sender_name', v_settings.sender_name, 'sender_email', v_settings.sender_email,
      'reply_to_email', v_settings.reply_to_email
    ),
    jsonb_build_object(
      'bank_name', v_settings.bank_name, 'account_holder', v_settings.account_holder,
      'account_number', v_settings.account_number, 'branch_code', v_settings.branch_code,
      'account_type', v_settings.account_type,
      'reference_instructions', v_settings.payment_reference_instructions
    ), v_settings.default_quote_terms,
    v_user_id, btrim(p_invoice ->> 'owner_name'), lower(btrim(p_invoice ->> 'owner_email'))
  ) returning id into v_invoice_id;
  insert into public.commercial_invoice_line_items (
    invoice_id, description, quantity, unit_amount, sort_order
  ) select v_invoice_id, btrim(item.value ->> 'description'),
      (item.value ->> 'quantity')::numeric, (item.value ->> 'unit_amount')::numeric,
      item.ordinality - 1
    from jsonb_array_elements(p_items) with ordinality item;
  insert into public.ops_activity_log (message, collection, record_id, action)
  values ('Invoice draft created', 'commercial_invoices', v_invoice_id, 'created');
  return jsonb_build_object('status', 'ok', 'invoice_id', v_invoice_id);
end;
$$;

