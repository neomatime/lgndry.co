-- Quotes, invoices and payment-gated booking for the OPS Command Center.

begin;

create table public.commercial_quotes (
  id uuid primary key default gen_random_uuid(),
  reference_number bigint generated by default as identity,
  revision integer not null default 1 check (revision > 0),
  supersedes_id uuid references public.commercial_quotes (id) on delete restrict,
  client_id uuid not null references public.clients (id) on delete restrict,
  contact_id uuid not null references public.client_contacts (id) on delete restrict,
  enquiry_id uuid references public.enquiries (id) on delete restrict,
  project_id uuid references public.projects (id) on delete restrict,
  title text not null check (length(btrim(title)) between 1 and 240),
  overview text,
  services text[] not null default '{}',
  location text,
  status text not null default 'Draft'
    check (status in ('Draft', 'Sent', 'Approved', 'Expired', 'Superseded', 'Void')),
  currency text not null default 'ZAR' check (currency = 'ZAR'),
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  discount_amount numeric(12, 2) not null default 0 check (discount_amount >= 0),
  total numeric(12, 2) not null default 0 check (total >= 0),
  retainer_percentage numeric(5, 2) not null
    check (retainer_percentage > 0 and retainer_percentage <= 100),
  terms text not null default '',
  valid_until date,
  approval_token_hash text unique,
  issued_at timestamptz,
  approved_at timestamptz,
  approved_by_name text,
  approved_by_email text,
  company_snapshot jsonb,
  payment_snapshot jsonb,
  owner_user_id uuid references auth.users (id) on delete set null,
  owner_name text not null,
  owner_email text not null,
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint commercial_quotes_reference_revision_key unique (reference_number, revision),
  constraint commercial_quotes_amounts_check check (
    discount_amount <= subtotal and total = subtotal - discount_amount
  ),
  constraint commercial_quotes_issue_check check (
    (status = 'Draft' and issued_at is null)
    or (status <> 'Draft' and issued_at is not null)
  ),
  constraint commercial_quotes_approval_check check (
    (status = 'Approved' and approved_at is not null)
    or (status <> 'Approved' and approved_at is null)
  )
);

create table public.commercial_quote_line_items (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references public.commercial_quotes (id) on delete cascade,
  description text not null check (length(btrim(description)) between 1 and 500),
  quantity numeric(10, 2) not null check (quantity > 0),
  unit_amount numeric(12, 2) not null check (unit_amount >= 0),
  line_total numeric(12, 2) generated always as (round(quantity * unit_amount, 2)) stored,
  sort_order integer not null check (sort_order >= 0),
  created_at timestamptz not null default now(),
  unique (quote_id, sort_order) deferrable initially deferred
);

create table public.commercial_invoices (
  id uuid primary key default gen_random_uuid(),
  reference_number bigint generated always as identity unique,
  quote_id uuid references public.commercial_quotes (id) on delete restrict,
  client_id uuid not null references public.clients (id) on delete restrict,
  contact_id uuid not null references public.client_contacts (id) on delete restrict,
  enquiry_id uuid references public.enquiries (id) on delete restrict,
  project_id uuid references public.projects (id) on delete restrict,
  title text not null check (length(btrim(title)) between 1 and 240),
  overview text,
  notes text,
  billing_type text not null default 'Standard'
    check (billing_type in ('Standard', 'Deposit', 'Balance')),
  status text not null default 'Draft' check (status in ('Draft', 'Sent', 'Paid', 'Void')),
  currency text not null default 'ZAR' check (currency = 'ZAR'),
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  discount_amount numeric(12, 2) not null default 0 check (discount_amount >= 0),
  total numeric(12, 2) not null default 0 check (total >= 0),
  paid_amount numeric(12, 2) not null default 0 check (paid_amount >= 0),
  issue_date date,
  due_date date,
  sent_at timestamptz,
  paid_at timestamptz,
  voided_at timestamptz,
  company_snapshot jsonb not null,
  payment_snapshot jsonb not null,
  terms_snapshot text not null default '',
  owner_user_id uuid references auth.users (id) on delete set null,
  owner_name text not null,
  owner_email text not null,
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint commercial_invoices_amounts_check check (
    discount_amount <= subtotal and total = subtotal - discount_amount and paid_amount <= total
  ),
  constraint commercial_invoices_dates_check check (
    issue_date is null or due_date is null or issue_date <= due_date
  ),
  constraint commercial_invoices_paid_check check (
    (status = 'Paid' and paid_at is not null and paid_amount = total)
    or (status <> 'Paid' and paid_at is null)
  ),
  constraint commercial_invoices_void_check check (
    (status = 'Void' and voided_at is not null) or (status <> 'Void' and voided_at is null)
  )
);

create unique index commercial_deposit_invoice_quote_idx
  on public.commercial_invoices (quote_id)
  where quote_id is not null and billing_type = 'Deposit';

create table public.commercial_invoice_line_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.commercial_invoices (id) on delete cascade,
  description text not null check (length(btrim(description)) between 1 and 500),
  quantity numeric(10, 2) not null check (quantity > 0),
  unit_amount numeric(12, 2) not null check (unit_amount >= 0),
  line_total numeric(12, 2) generated always as (round(quantity * unit_amount, 2)) stored,
  sort_order integer not null check (sort_order >= 0),
  created_at timestamptz not null default now(),
  unique (invoice_id, sort_order) deferrable initially deferred
);

create table public.commercial_payments (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.commercial_invoices (id) on delete restrict,
  amount numeric(12, 2) not null check (amount > 0),
  paid_on date not null,
  method text not null check (method in ('Bank Transfer', 'Card', 'Cash', 'Other')),
  reference text,
  notes text,
  recorded_by uuid references auth.users (id) on delete set null,
  recorded_by_name text not null,
  created_at timestamptz not null default now()
);

create index commercial_quotes_client_idx on public.commercial_quotes (client_id, created_at desc);
